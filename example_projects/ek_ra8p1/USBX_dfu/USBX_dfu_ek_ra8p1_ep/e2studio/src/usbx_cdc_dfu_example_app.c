static void usbx_peri_cdc_dfu_init(void)
{
    UINT status = UX_SUCCESS;
    fsp_err_t err = FSP_SUCCESS;

    /* Initialize the USBX device stack */
    status = ux_device_stack_initialize(g_device_framework_hi_speed,
                                        DEVICE_FRAME_LENGTH_CDC_HI_SPEED,
                                        g_device_framework_full_speed,
                                        DEVICE_FRAME_LENGTH_CDC_FULL_SPEED,
                                        g_string_framework,
                                        STRING_FRAMEWORK_CDC_LENGTH,
                                        g_language_id_framework,
                                        CDC_LANGUAGE_ID_FRAME_WORK_LENGTH,
                                        usbx_cdc_dfu_device_status_change_callback);
    if (UX_SUCCESS != status)
    {
        PRINT_ERR_STR("ux_device_stack_initialize API failed");
        ERROR_TRAP(status);
        return;
    }
    s_device_stack_initialized = true;
    PRINT_INFO_STR("USBX device stack initialized successfully");

    /* The activate command is used when the host has sent a SET_CONFIGURATION command
     * and this interface has to be mounted. Endpoints have to be mounted and
     * the peripheral CDC-DFU device thread needs to be activated. */
    s_ux_device_class_cdc_parameter.ux_slave_class_cdc_acm_instance_activate = usbx_cdc_instance_activate;

    /* The deactivate command is used when the device has been extracted.
     * The device endpoints have to be dismounted and the peripheral CDC-DFU device thread canceled. */
    s_ux_device_class_cdc_parameter.ux_slave_class_cdc_acm_instance_deactivate = usbx_cdc_instance_deactivate;

    /* Register the CDC ACM class */
    status = ux_device_stack_class_register(_ux_system_slave_class_cdc_acm_name, ux_device_class_cdc_acm_entry,
                                            CONFIG_NUMB, INTERFACE_NUMB0, (void *)&s_ux_device_class_cdc_parameter);
    if (UX_SUCCESS != status)
    {
        PRINT_ERR_STR("ux_device_stack_class_register API failed for CDC ACM");
        ERROR_TRAP(status);
        return;
    }
    s_cdc_class_registered = true;
    PRINT_INFO_STR("USBX CDC ACM class registered successfully");

    g_ux_dfu_peri_class_parameter.ux_slave_class_dfu_parameter_framework = g_device_framework_full_speed;
    g_ux_dfu_peri_class_parameter.ux_slave_class_dfu_parameter_framework_length = DEVICE_FRAME_LENGTH_CDC_FULL_SPEED;

    /* Register the DFU Run-Time class */
    status = ux_device_stack_class_register(_ux_system_slave_class_dfu_name, ux_device_class_dfu_entry, CONFIG_NUMB,
                                            INTERFACE_NUMB2, (void *)&g_ux_dfu_peri_class_parameter);

    if (UX_SUCCESS != status)
    {
        PRINT_ERR_STR("ux_device_stack_class_register API failed for DFU");
        ERROR_TRAP(status);
        return;
    }
    PRINT_INFO_STR("USBX DFU class registered successfully");

    /* Start CDC DFU USB module */
    err = usb_init(&g_basic1_ctrl, &g_basic1_cfg);
    if (FSP_SUCCESS != err)
    {
        PRINT_ERR_STR("usb_init for CDC DFU USB failed");
        ERROR_TRAP(err);
        return;
    }
    s_usb_opened = true;
    PRINT_INFO_STR("USBX peripheral CDC DFU device initialized successfully");
}

/*******************************************************************************************************************//**
 * @brief     This function activates the PCDC instance.
 * @param[in] peri_cdc_device_instance  Pointer to the area that stores the instance pointer.
 * @retval    None.
 **********************************************************************************************************************/
static void usbx_cdc_instance_activate(void * peri_cdc_device_instance)
{
    /* Save the peripheral CDC device instance */
    sp_peri_cdc_device = (UX_SLAVE_CLASS_CDC_ACM *)peri_cdc_device_instance;
    tx_semaphore_put(&g_peri_cdc_dfu_device_connect_semaphore0);
    PRINT_INFO_STR("USBX peripheral CDC device activated");
    tx_thread_sleep(THREAD_SLEEP_10);
}

/*******************************************************************************************************************//**
 * @brief     This function deactivates the PCDC instance.
 * @param[in] peri_cdc_device_instance  Pointer to the area that stores the instance pointer.
 * @retval    None.
 **********************************************************************************************************************/
static void usbx_cdc_instance_deactivate(void * peri_cdc_device_instance)
{
    FSP_PARAMETER_NOT_USED(peri_cdc_device_instance);

    /* Deactivate the peripheral CDC device instance */
    sp_peri_cdc_device = NULL;
    tx_semaphore_put(&g_peri_cdc_dfu_device_connect_semaphore0);
    PRINT_INFO_STR("USBX peripheral CDC device deactivated");
    tx_thread_sleep(THREAD_SLEEP_10);
}

/*******************************************************************************************************************//**
 * @brief     This function cleans up initialized USBX Run-Time resources.
 * @param[in] None.
 * @retval    None.
 **********************************************************************************************************************/
static void runtime_resources_cleanup(void)
{
    UINT status = UX_SUCCESS;
    fsp_err_t err = FSP_SUCCESS;

    if (s_usb_opened)
    {
        err = usb_deinit(&g_basic1_ctrl);
        if ((FSP_SUCCESS == err) || (FSP_ERR_USB_NOT_OPEN == err))
        {
            s_usb_opened = false;
        }
    }

    if (s_cdc_class_registered)
    {
        status = ux_device_stack_class_unregister(_ux_system_slave_class_cdc_acm_name,
                                                  ux_device_class_cdc_acm_entry);
        if (UX_SUCCESS == status)
        {
            s_cdc_class_registered = false;
        }
    }

    if (s_device_stack_initialized)
    {
        status = ux_device_stack_uninitialize();
        if (UX_SUCCESS == status)
        {
            s_device_stack_initialized = false;
        }
    }
}

/*******************************************************************************************************************//**
 * @brief     This function is a callback for USBX Peripheral CDC device status changes.
 * @param[in] status                    USB status value indicating the current state or event.
 * @retval    UX_SUCCESS                Always returns success to indicate the status was handled.
 **********************************************************************************************************************/
static UINT usbx_cdc_dfu_device_status_change_callback(ULONG status)
{
    if (UX_DEVICE_ATTACHED == status)
    {
        PRINT_INFO_STR("USBX peripheral CDC device attached");
        tx_thread_sleep(THREAD_SLEEP_10);
    }
    else if (UX_DEVICE_ADDRESSED == status)
    {
        PRINT_INFO_STR("USBX peripheral CDC device addressed");
        tx_thread_sleep(THREAD_SLEEP_10);
    }
    else if (UX_DEVICE_CONFIGURED == status)
    {
        PRINT_INFO_STR("USBX peripheral CDC device configured");
        tx_thread_sleep(THREAD_SLEEP_10);
    }
    else if (UX_DEVICE_SUSPENDED == status)
    {
        PRINT_INFO_STR("USBX peripheral CDC device suspended");
        tx_thread_sleep(THREAD_SLEEP_10);
    }
    else if (UX_DEVICE_RESUMED == status)
    {
        PRINT_INFO_STR("USBX peripheral CDC device resumed");
        tx_thread_sleep(THREAD_SLEEP_10);
    }
    else if (UX_DEVICE_FORCE_DISCONNECT == status)
    {
        PRINT_INFO_STR("USBX peripheral CDC device force disconnected");

        /* Release the Run-Time USB resources before switching to DFU mode */
        current_drivers_un_init();
    }
    else if (UX_DEVICE_REMOVED == status)
    {
        if (_ux_system_slave -> ux_system_slave_device_dfu_state_machine == UX_SYSTEM_DFU_STATE_APP_DETACH)
        {
            tx_event_flags_set(&ra_dfu_detach_event, DETACH_EVENT_FLAG, TX_OR);
            sp_peri_cdc_device = NULL;
        }

        PRINT_INFO_STR("USBX peripheral CDC device removed");
        tx_thread_sleep(THREAD_SLEEP_10);
    }
    else
    {
        /* Do nothing */
    }

    return UX_SUCCESS;
}
